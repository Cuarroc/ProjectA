// DS-H-03: the four role figures of docs/design/hall/ASSETS.md §6, feet in the bottom four rows. A figure
// is BODY with its role's head rows laid over it (silhouette and prop); a pose lays its rows over the
// role's `ready` frame, so a pose is a delta (§5) shared by all four roles. In an overlay row "_" keeps
// the pixel below. "6" is drawn as the role colour and becomes the role's own palette index.
// poses.ts names the StateForm behind each pose.
type Overlay = Readonly<Record<number, string>>;
const over = (base: Raster, rows: Overlay): Raster =>
  base.map((row, y) => [...row].map((c, x) => (rows[y]?.[x] ?? "_") === "_" ? c : rows[y][x]).join(""));

