import { act, cleanup, fireEvent, render, screen, within } from "@testing-library/react";
import { afterEach, beforeEach, expect, it, vi } from "vitest";

const mocks = vi.hoisted(() => ({ invoke: vi.fn() }));
vi.mock("@tauri-apps/api/core", () => ({ invoke: mocks.invoke }));
vi.mock("@tauri-apps/api/event", () => ({ listen: vi.fn(async () => () => {}) }));

import ShellMount from "./ShellMount";
import { writeActiveProjectId } from "../../lib/activeProject";
import { setFeatureFlagEnabled } from "../../flags/featureFlags";

const note = { id: "l1", project_id: "p1", worker_id: "w1", profile_id: "pr1", pattern_label: null, content: "Original insight", status: "pending", created_at: 1 };
const second = { ...note, id: "l2", content: "Second insight" };
const deferred = () => {
  let resolve!: (value: unknown) => void;
  let reject!: (reason: Error) => void;
  const promise = new Promise((yes, no) => { resolve = yes; reject = no; });
  return { promise, resolve, reject };
};
let read: () => Promise<unknown>, approve: () => Promise<unknown>, reject: () => Promise<unknown>;
const unexpected: string[] = [];
const calls = (name: string) => mocks.invoke.mock.calls.filter(([command]) => command === name);
const go = (path: string) => act(async () => { window.location.hash = `#${path}`; window.dispatchEvent(new HashChangeEvent("hashchange")); });
const mount = () => render(<ShellMount>{() => <input aria-label="Mounted session" defaultValue="draft" />}</ShellMount>);
const row = (index = 0) => within(screen.getAllByRole("textbox", { name: "Lektion bearbeiten" })[index].closest("li")!);
const edit = (index: number, value: string) => fireEvent.change(row(index).getByRole("textbox", { name: "Lektion bearbeiten" }), { target: { value } });

beforeEach(() => {
  localStorage.clear();
  setFeatureFlagEnabled("weitere_bereiche", true);
  writeActiveProjectId("p1");
  window.location.hash = "#/gedaechtnis";
  unexpected.length = 0;
  read = async () => [note, second];
  approve = reject = async () => undefined;
  mocks.invoke.mockReset().mockImplementation(async (command: string) => {
    if (command === "list_learnings") return read();
    if (command === "approve_learning") return approve();
    if (command === "reject_learning") return reject();
    if (["list_projects", "get_provider_overview", "get_quota_state"].includes(command)) return [];
    if (command === "get_emergency_stop") return false;
    if (command === "get_panic_notice") return { current: null, previous: null };
    unexpected.push(command);
    throw new Error(`Unexpected IPC: ${command}`);
  });
});
afterEach(() => { cleanup(); expect(unexpected).toEqual([]); });

it("mounts project lessons on the existing route and approves only the edited text", async () => {
  const pending = deferred();
  approve = () => pending.promise;
  const { container } = mount();
  expect(await screen.findByRole("region", { name: "Lektionen zur Freigabe" })).toBeVisible();
  await screen.findByText("Original insight");
  expect(calls("list_learnings")).toEqual([["list_learnings", { projectId: "p1" }]]);
  expect(container.querySelector(".g-mount")).toHaveAttribute("data-fresh", "on");
  edit(0, "   ");
  expect(row().getByRole("button", { name: "Übernehmen" })).toBeDisabled();
  fireEvent.click(row().getByRole("button", { name: "Übernehmen" }));
  expect(calls("approve_learning")).toEqual([]);
  edit(0, "  Edited insight  ");
  expect(calls("approve_learning")).toEqual([]);
  fireEvent.click(row().getByRole("button", { name: "Übernehmen" }));
  expect(calls("approve_learning")).toEqual([["approve_learning", { id: "l1", text: "Edited insight" }]]);
  for (const name of ["Übernehmen", "Verwerfen"]) expect(row().getByRole("button", { name })).toBeDisabled();
  expect(row().getByRole("textbox")).toBeDisabled();
  expect(row(1).getByRole("textbox")).toBeEnabled();
  expect(row(1).getByRole("button", { name: "Übernehmen" })).toBeEnabled();
  await act(async () => pending.resolve(undefined));
  expect(screen.queryByText("Original insight")).toBeNull();
  expect(screen.getByText("Ins Playbook übernommen.")).toBeVisible();
  expect(calls("approve_learning")).toHaveLength(1);
});

it("retains edits through failed decisions and reads without resurrecting decided rows", async () => {
  approve = reject = async () => { throw new Error("denied"); };
  mount();
  await screen.findByText("Original insight");
  edit(0, "  Keep this draft  ");
  fireEvent.click(row().getByRole("button", { name: "Übernehmen" }));
  await screen.findByText("Die Lektion konnte nicht übernommen werden. Bitte noch einmal versuchen.");
  expect(row().getByRole("textbox")).toHaveValue("  Keep this draft  ");
  fireEvent.click(row().getByRole("button", { name: "Verwerfen" }));
  await screen.findByText("Die Lektion konnte nicht verworfen werden. Bitte noch einmal versuchen.");
  expect(row().getByRole("textbox")).toHaveValue("  Keep this draft  ");
  read = async () => { throw new Error("offline"); };
  reject = async () => undefined;
  edit(1, "Live draft");
  fireEvent.click(row().getByRole("button", { name: "Verwerfen" }));
  await screen.findByText("Die Liste konnte nach der Entscheidung nicht erneut gelesen werden.");
  expect(screen.queryByText("Original insight")).toBeNull();
  expect(screen.queryByText("Keine offenen Lektionen.")).toBeNull();
  const pending = deferred();
  read = () => pending.promise;
  fireEvent.click(screen.getByRole("button", { name: "Erneut versuchen" }));
  edit(0, "Newer live draft");
  await act(async () => pending.resolve([note, second]));
  expect(screen.queryByText("Original insight")).toBeNull();
  expect(row().getByRole("textbox")).toHaveValue("Newer live draft");
  expect(calls("approve_learning")).toEqual([["approve_learning", { id: "l1", text: "Keep this draft" }]]);
  expect(calls("reject_learning")).toEqual([["reject_learning", { id: "l1" }], ["reject_learning", { id: "l1" }]]);
  read = async () => { throw new Error("offline"); };
  fireEvent.click(row().getByRole("button", { name: "Verwerfen" }));
  await screen.findByText("Die Liste konnte nach der Entscheidung nicht erneut gelesen werden.");
  expect(screen.queryByText("Keine offenen Lektionen.")).toBeNull();
});

it("isolates project visits from late reads and decisions across p1 p2 p1", async () => {
  const old = deferred(), fresh = deferred(), p2 = deferred(), p1 = deferred();
  approve = () => old.promise;
  mount();
  await screen.findByText("Original insight");
  edit(0, "Old project draft");
  fireEvent.click(row().getByRole("button", { name: "Übernehmen" }));
  read = () => p2.promise;
  await act(async () => writeActiveProjectId("p2"));
  expect(screen.queryByRole("textbox", { name: "Lektion bearbeiten" })).toBeNull();
  read = () => p1.promise;
  await act(async () => writeActiveProjectId("p1"));
  await act(async () => p2.resolve([{ ...note, content: "Stale project reply" }]));
  expect(screen.queryByText("Stale project reply")).toBeNull();
  await act(async () => p1.resolve([note]));
  expect(row().getByRole("textbox")).toHaveValue("Original insight");
  approve = () => fresh.promise;
  fireEvent.click(row().getByRole("button", { name: "Übernehmen" }));
  await act(async () => old.resolve(undefined));
  expect(row().getByRole("textbox")).toBeDisabled();
  expect(screen.queryByText("Ins Playbook übernommen.")).toBeNull();
  expect(calls("list_learnings")).toEqual([["list_learnings", { projectId: "p1" }], ["list_learnings", { projectId: "p2" }], ["list_learnings", { projectId: "p1" }]]);
  await act(async () => fresh.resolve(undefined));
  expect(screen.queryByText("Original insight")).toBeNull();
  expect(calls("approve_learning")).toEqual([["approve_learning", { id: "l1", text: "Old project draft" }], ["approve_learning", { id: "l1", text: "Original insight" }]]);
});

it("keeps hidden recovery and legacy drafts while resetting lessons on route visits", async () => {
  writeActiveProjectId(null);
  const view = mount();
  expect(await screen.findByText("Kein Projekt gewählt.")).toBeVisible();
  expect(calls("list_learnings")).toEqual([]);
  const session = screen.getByDisplayValue("draft");
  fireEvent.change(session, { target: { value: "kept" } });
  await act(async () => setFeatureFlagEnabled("weitere_bereiche", false));
  await act(async () => writeActiveProjectId("p1"));
  await go("/gedaechtnis/");
  expect(screen.getByText("Dieser Bereich ist noch nicht verbunden und ausgeblendet.")).toBeVisible();
  expect(screen.getByRole("link", { name: "Weitere Bereiche in den Einstellungen einschalten" })).toHaveAttribute("href", "#/einstellungen");
  expect(screen.queryByRole("region", { name: "Lektionen zur Freigabe" })).toBeNull();
  expect(calls("list_learnings")).toEqual([]);
  expect(calls("approve_learning")).toEqual([]);
  expect(calls("reject_learning")).toEqual([]);
  await act(async () => setFeatureFlagEnabled("weitere_bereiche", true));
  await screen.findByText("Original insight");
  edit(0, "Unsent route draft");
  const pending = deferred();
  approve = () => pending.promise;
  fireEvent.click(row().getByRole("button", { name: "Übernehmen" }));
  await go("/nirgends");
  const reads = calls("list_learnings").length;
  await act(async () => pending.resolve(undefined));
  expect(calls("list_learnings")).toHaveLength(reads);
  await go("/gedaechtnis/");
  await screen.findByText("Original insight");
  expect(row().getByRole("textbox")).toHaveValue("Original insight");
  expect(screen.getByDisplayValue("kept")).toBe(session);
  const late = deferred();
  read = () => late.promise;
  await go("/nirgends");
  await go("/gedaechtnis");
  view.unmount();
  const before = mocks.invoke.mock.calls.length;
  await act(async () => late.resolve([note]));
  expect(mocks.invoke.mock.calls).toHaveLength(before);
});
